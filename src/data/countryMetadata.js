export function getCountryMeta(code) {
  if (!code) return null
  return COUNTRY_METADATA[String(code).toUpperCase()] || null
}

export function getCountryName(code) {
  const m = getCountryMeta(code)
  return m ? m.name : code
}

export function getSortedCountries() {
  return Object.values(COUNTRY_METADATA).sort((a, b) => a.name.localeCompare(b.name))
}

