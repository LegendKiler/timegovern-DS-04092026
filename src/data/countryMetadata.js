export function getCountriesByRegion() {
  const byRegion = {}
  for (const c of Object.values(COUNTRY_METADATA)) {
    if (!byRegion[c.region]) byRegion[c.region] = []
    byRegion[c.region].push(c)
  }
  for (const r of Object.keys(byRegion)) {
    byRegion[r].sort((a, b) => a.name.localeCompare(b.name))
  }
  return byRegion
}

export function getCurrencySymbol(code) {
  const m = getCountryMeta(code)
  if (m && m.currencySymbol) return m.currencySymbol
  return '$'
}
