// ---- Helpers ----

export function getCountryMeta(code) {
  if (!code) return null
  return COUNTRY_METADATA[String(code).toUpperCase()] || null
}

export function hasFullMetadata(code) {
  const m = getCountryMeta(code)
  return !!(m && !m.todo)
}

export function getAllCodes() {
  return Object.keys(COUNTRY_METADATA)
}

export function getLocalAuthorityCountries() {
  return Object.values(COUNTRY_METADATA).filter(m => m.localAuthorities.length > 0)
}
